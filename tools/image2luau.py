#!/usr/bin/env python3
"""Convert a binary image (e.g. a Linux kernel Image) into Luau ModuleScripts.

    python3 tools/image2luau.py <input> <output-dir> [--name NAME] [--chunk-chars N]

The data is LZ4-block compressed, base64 encoded and split across
Chunk001.luau, Chunk002.luau, ... (each returns one string) with an init.luau
that describes the image. src/shared/Emulator/ImageLoader.luau reverses this.

LZ4 is used because its decoder is tiny and fast in Luau. The compressor below
is a plain greedy hash-chain implementation of the LZ4 block format.
"""
import argparse
import base64
import hashlib
import os
import sys

MIN_MATCH = 4
MAX_OFFSET = 65535
HASH_BITS = 16


def lz4_compress(data: bytes) -> bytes:
    n = len(data)
    out = bytearray()
    table = {}
    anchor = 0
    i = 0
    # LZ4 requires the last 5 bytes to be literals and matches to start
    # at least 12 bytes before the end.
    match_limit = n - 12
    end_literals = n - 5

    def emit(literals: bytes, offset: int, match_len: int):
        lit_len = len(literals)
        token_lit = min(lit_len, 15)
        token_match = 0 if match_len < 0 else min(match_len - MIN_MATCH, 15)
        out.append((token_lit << 4) | token_match)
        if lit_len >= 15:
            rest = lit_len - 15
            while rest >= 255:
                out.append(255)
                rest -= 255
            out.append(rest)
        out.extend(literals)
        if match_len < 0:
            return
        out.append(offset & 0xFF)
        out.append(offset >> 8)
        if match_len - MIN_MATCH >= 15:
            rest = match_len - MIN_MATCH - 15
            while rest >= 255:
                out.append(255)
                rest -= 255
            out.append(rest)

    while i < match_limit:
        key = data[i:i + 4]
        candidate = table.get(key)
        table[key] = i
        if candidate is not None and i - candidate <= MAX_OFFSET:
            length = 4
            while i + length < end_literals and data[candidate + length] == data[i + length]:
                length += 1
            emit(data[anchor:i], i - candidate, length)
            # Index a few positions inside the match to improve later matches.
            for j in range(i + 1, min(i + length, match_limit), 2):
                table[data[j:j + 4]] = j
            i += length
            anchor = i
        else:
            i += 1
    emit(data[anchor:], 0, -1)
    return bytes(out)


def lz4_decompress(src: bytes, size: int) -> bytes:
    out = bytearray()
    i = 0
    while i < len(src):
        token = src[i]
        i += 1
        lit = token >> 4
        if lit == 15:
            while True:
                b = src[i]
                i += 1
                lit += b
                if b != 255:
                    break
        out.extend(src[i:i + lit])
        i += lit
        if i >= len(src):
            break
        offset = src[i] | (src[i + 1] << 8)
        i += 2
        mlen = token & 15
        if mlen == 15:
            while True:
                b = src[i]
                i += 1
                mlen += b
                if b != 255:
                    break
        mlen += MIN_MATCH
        start = len(out) - offset
        for k in range(mlen):
            out.append(out[start + k])
    assert len(out) == size, (len(out), size)
    return bytes(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input")
    ap.add_argument("output_dir")
    ap.add_argument("--name", default=None, help="display name stored in init.luau")
    ap.add_argument("--description", default="", help="description stored in init.luau")
    ap.add_argument("--chunk-chars", type=int, default=196_000, help="max base64 characters per module")
    args = ap.parse_args()

    with open(args.input, "rb") as f:
        raw = f.read()
    packed = lz4_compress(raw)
    if lz4_decompress(packed, len(raw)) != raw:
        sys.exit("internal error: LZ4 round trip failed")
    encoded = base64.b64encode(packed).decode("ascii")
    # Base64 chunks must split on 4-character boundaries.
    step = args.chunk_chars - args.chunk_chars % 4
    chunks = [encoded[i:i + step] for i in range(0, len(encoded), step)]

    os.makedirs(args.output_dir, exist_ok=True)
    for old in os.listdir(args.output_dir):
        if old.startswith("Chunk") and old.endswith(".luau"):
            os.remove(os.path.join(args.output_dir, old))
    for n, chunk in enumerate(chunks, 1):
        with open(os.path.join(args.output_dir, f"Chunk{n:03d}.luau"), "w") as f:
            f.write("-- Generated by tools/image2luau.py. Do not edit.\n")
            f.write(f'return "{chunk}"\n')

    name = args.name or os.path.basename(args.input)
    sha = hashlib.sha256(raw).hexdigest()
    with open(os.path.join(args.output_dir, "init.luau"), "w") as f:
        f.write("-- Generated by tools/image2luau.py. Do not edit.\n")
        f.write("return {\n")
        f.write(f'\tname = "{name}",\n')
        f.write(f'\tdescription = "{args.description}",\n')
        f.write('\tformat = "lz4+base64",\n')
        f.write(f"\tsize = {len(raw)},\n")
        f.write(f"\tcompressedSize = {len(packed)},\n")
        f.write(f'\tsha256 = "{sha}",\n')
        f.write(f"\tchunks = {len(chunks)},\n")
        f.write("}\n")

    print(f"{args.input}: {len(raw)} bytes -> {len(packed)} compressed ({100 * len(packed) / len(raw):.1f}%) "
          f"-> {len(chunks)} modules in {args.output_dir}")


if __name__ == "__main__":
    main()
